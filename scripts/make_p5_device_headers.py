"""Write the P5 device headers (job F2, ADR-0008): the P5 TinyKAN and the s_hat concept regressor.

Host only. Never edits kan_model_weights.h / _v2.h / _v3.h or any existing output. Write-once: every
output must not exist yet.

  --p5-model   outputs/physio-concept-v1/p5_final_model.npz   (exact weights; not retrained)
  --regressor  outputs/physio-device-v1/sat_regressor_model.npz
writes
  firmware/Arduino Nano 33/include/kan_model_weights_p5.h   TinyKAN 5 -> 12 -> 1, scaler, imputation mean
  firmware/Arduino Nano 33/include/kan_sat_regressor_p5.h   regressor 5 -> 12 -> 1, target mean/std/clip
  outputs/xai-reference-headers/p5_device_inputs.csv.gz     the 48,662 P5 model inputs after imputation
                                                            (FP32 values), plus label: the table that
                                                            scripts/make_xai_reference_header.py reads
                                                            for the P5 label-0 reference
  outputs/xai-reference-headers/kan_p5_headers.json         provenance and every check below

Checks (any failure stops and removes what was written):
  * every FP32 literal parses back to the npz FP32 bits (train_tinykan_v2.parse_header);
  * FP32(imputation mean) == FP32(scaler mean) bit for bit, so beat-invalid inputs standardize to 0;
  * the regressor's scaler equals the P5 scaler bit for bit (one standardized vector feeds both);
  * header replica (lamaakal_models.HeaderKAN arithmetic: FP32 constants in float64) vs the npz
    replica (analyze_physio_concept.ArrayKAN) over all 48,662 rows: max |dP| and max |ds_hat|,
    required 0; both also reported against the torch outputs recorded with each model.

Run: C:\\Python314\\python.exe scripts/make_p5_device_headers.py
Then the label-0 reference with F1's generator (unchanged):
  C:\\Python314\\python.exe scripts/make_xai_reference_header.py \
    --model-header "firmware/Arduino Nano 33/include/kan_model_weights_p5.h" \
    --table outputs/xai-reference-headers/p5_device_inputs.csv.gz \
    --features r_beat,pi_beat,hr_bpm,sqi_template,sqi_ibi_ratio \
    --output "firmware/Arduino Nano 33/include/kan_xai_reference_p5.h" \
    --sidecar outputs/xai-reference-headers/kan_xai_reference_p5.json \
    --check-s3 outputs/physio-concept-v1/s3.json --check-s3-model P5
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import gzip
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import pandas as pd

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
from make_xai_reference_header import fp32_literal, rel  # noqa: E402
from train_tinykan_v2 import parse_header  # noqa: E402

ROOT = SCRIPTS.parent
INCLUDE = ROOT / "firmware/Arduino Nano 33/include"
P5_MODEL = ROOT / "outputs/physio-concept-v1/p5_final_model.npz"
REGRESSOR = ROOT / "outputs/physio-device-v1/sat_regressor_model.npz"
TABLE_OUT = ROOT / "outputs/xai-reference-headers/p5_device_inputs.csv.gz"
SIDECAR_OUT = ROOT / "outputs/xai-reference-headers/kan_p5_headers.json"
P5_HEADER = INCLUDE / "kan_model_weights_p5.h"
SAT_HEADER = INCLUDE / "kan_sat_regressor_p5.h"
FEATURES = ("r_beat", "pi_beat", "hr_bpm", "sqi_template", "sqi_ibi_ratio")
LAYER_KEYS = (("W", "w1", 1), ("B", "b1", 1), ("THETA", "theta1", 1), ("CENTERS", "centers1", 1), ("STEP", "step1", 1),
              ("W", "w2", 2), ("B", "b2", 2), ("THETA", "theta2", 2), ("CENTERS", "centers2", 2), ("STEP", "step2", 2))


def sha256(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def c_array(name, values):
    values = np.asarray(values, dtype=np.float32)
    dims = "".join(f"[{d}]" for d in values.shape)
    if values.ndim == 1:
        body = ", ".join(fp32_literal(v) + "f" for v in values)
        return f"const float {name}{dims} = {{\n    {body}\n}};\n"
    rows = ",\n".join("    {" + ", ".join(fp32_literal(v) + "f" for v in row) + "}" for row in values)
    return f"const float {name}{dims} = {{\n{rows}\n}};\n"


def c_scalar(name, value):
    return f"const float {name} = {fp32_literal(value)}f;\n"


def layer_block(prefix, arrays):
    text = ""
    for suffix, key, layer in LAYER_KEYS:
        if suffix == "W":
            shape = arrays[key].shape
            text += f"\n// Layer {layer}: {shape[1]} -> {shape[0]}\n"
        name = f"{prefix}{layer}_{suffix}"
        text += c_scalar(name, arrays[key]) if suffix == "STEP" else c_array(name, arrays[key])
    return text


def p5_header_text(p5, sources):
    return f"""// Auto-generated by scripts/make_p5_device_headers.py. Do not edit.
// P5 TinyKAN (job F2, ADR-0008): the exact weights of {sources['p5_model']}
// (sha256 {sources['p5_model_sha256']}), not retrained. 189 trainable parameters.
// 5 inputs in this order: {', '.join(FEATURES)}.
// Included only by -DOXY_MODEL_P5 builds (kan_inference.h); the v1/v2 images never see it.

#pragma once

#define KAN_INPUT_DIM 5
#define KAN_HIDDEN_DIM 12
#define KAN_KNOTS 8

// StandardScaler Parameters
{c_array("SCALER_MEAN", p5["scaler_mean"])}
{c_array("SCALER_STD", p5["scaler_std"])}
// Beat-invalid windows: every input takes its imputation mean (the all-window beat-valid mean).
// In FP32 it equals SCALER_MEAN bit for bit (checked by the generator), so the input standardizes to 0.
{c_array("KAN_P5_IMPUTATION_MEAN", p5["imputation_mean"])}{layer_block("KAN", p5)}
const float KAN_DECISION_THRESHOLD = 0.50f;
"""


def sat_header_text(reg, bounds, sources):
    return f"""// Auto-generated by scripts/make_p5_device_headers.py. Do not edit.
// Concept regressor for estimated ScalcO2 (s_hat, the model saturation estimate) on the P5 image
// (job F2, ADR-0008): {sources['regressor']} (sha256 {sources['regressor_sha256']}).
// Displayed only: s_hat never feeds the risk score or the explanation. Not an oxygen reading; uncalibrated
// for the MAX30102. Included only by -DOXY_MODEL_P5 builds.
//
// Input: the P5 standardized vector. The regressor's scaler equals the P5 scaler bit for bit
// (checked by the generator), so it reuses SCALER_MEAN / SCALER_STD of kan_model_weights_p5.h.
// s_hat = output * KANSAT_TARGET_STD + KANSAT_TARGET_MEAN; output is the 5 -> 12 -> 1 KAN with a
// linear output (no sigmoid), the arithmetic of kan_layer1_forward / kan_layer2_forward.

#pragma once

#if KAN_INPUT_DIM != 5
#error "kan_sat_regressor_p5.h takes the 5 P5 inputs"
#endif

#define KANSAT_HIDDEN_DIM 12
#define KANSAT_KNOTS 8
{layer_block("KANSAT", reg)}
// Training target: window-median ScalcO2 clipped to [KANSAT_TARGET_CLIP_LO, KANSAT_TARGET_CLIP_HI],
// standardized with these (population std). s_hat is not clipped (as in Stage 4).
{c_scalar("KANSAT_TARGET_MEAN", reg["target_mean"])}{c_scalar("KANSAT_TARGET_STD", reg["target_std"])}{c_scalar("KANSAT_TARGET_CLIP_LO", reg["target_clip"][0])}{c_scalar("KANSAT_TARGET_CLIP_HI", reg["target_clip"][1])}
// Bounds of s_hat over every input: mean + std * [min(0, min theta2), max(0, max theta2)] (the cubic
// B-spline basis is non-negative and sums to at most 1). Used to size BLE field 10.
#define KANSAT_S_HAT_BOUND_LO {bounds[0]:.4f}f
#define KANSAT_S_HAT_BOUND_HI {bounds[1]:.4f}f
"""


def load_npz(path):
    with np.load(path) as z:
        return {k: z[k] for k in z.files}


def header_arrays(path, prefix):
    raw = parse_header(path)
    return {key: np.asarray(raw[f"{prefix}{layer}_{suffix}"], dtype=np.float32) for suffix, key, layer in LAYER_KEYS}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--p5-model", type=Path, default=P5_MODEL)
    parser.add_argument("--regressor", type=Path, default=REGRESSOR)
    args = parser.parse_args()
    outputs = (P5_HEADER, SAT_HEADER, TABLE_OUT, SIDECAR_OUT)
    for path in outputs:
        if path.exists():
            parser.error(f"{path} exists; refusing to overwrite")
    import analyze_physio_concept as apc

    p5, reg = load_npz(args.p5_model), load_npz(args.regressor)
    if tuple(str(f) for f in p5["features"]) != FEATURES or tuple(str(f) for f in reg["features"]) != FEATURES:
        raise SystemExit("Feature order differs from r_beat, pi_beat, hr_bpm, sqi_template, sqi_ibi_ratio")
    checks = {}
    as32 = lambda a: np.asarray(a, dtype=np.float32)  # noqa: E731
    checks["imputation_equals_scaler_mean_fp32_bits"] = bool(np.array_equal(as32(p5["imputation_mean"]).view(np.uint32),
                                                                            as32(p5["scaler_mean"]).view(np.uint32)))
    checks["regressor_scaler_equals_p5_scaler"] = bool(np.array_equal(reg["scaler_mean"], p5["scaler_mean"])
                                                       and np.array_equal(reg["scaler_std"], p5["scaler_std"]))
    if not (checks["imputation_equals_scaler_mean_fp32_bits"] and checks["regressor_scaler_equals_p5_scaler"]):
        raise SystemExit(f"Scaler/imputation check failed: {checks}")
    theta2 = as32(reg["theta2"]).astype(np.float64)[0]
    t_mean, t_std = float(np.float32(reg["target_mean"])), float(np.float32(reg["target_std"]))
    bounds = (t_mean + t_std * min(0.0, theta2.min()), t_mean + t_std * max(0.0, theta2.max()))
    if not (-99.9 < bounds[0] < bounds[1] < 999.9):
        raise SystemExit(f"s_hat bounds {bounds} would not print in 5 characters with one decimal")
    sources = {"p5_model": rel(args.p5_model), "p5_model_sha256": sha256(args.p5_model),
               "regressor": rel(args.regressor), "regressor_sha256": sha256(args.regressor)}

    written = []
    try:
        for path, text in ((P5_HEADER, p5_header_text(p5, sources)), (SAT_HEADER, sat_header_text(reg, bounds, sources))):
            with path.open("x", encoding="utf-8", newline="\n") as stream:
                stream.write(text)
            written.append(path)
        # Round trip: every literal parses back to the npz FP32 bits.
        parsed = parse_header(P5_HEADER)
        trip = {"SCALER_MEAN": p5["scaler_mean"], "SCALER_STD": p5["scaler_std"], "KAN_P5_IMPUTATION_MEAN": p5["imputation_mean"]}
        for name, expected in trip.items():
            if not np.array_equal(as32(parsed[name]).view(np.uint32), as32(expected).view(np.uint32)):
                raise SystemExit(f"{name} does not round-trip")
        for prefix, path, arrays in (("KAN", P5_HEADER, p5), ("KANSAT", SAT_HEADER, reg)):
            back = header_arrays(path, prefix)
            for key, value in back.items():
                if not np.array_equal(value.view(np.uint32), as32(arrays[key]).view(np.uint32)):
                    raise SystemExit(f"{prefix} {key} does not round-trip")
        sat_parsed = parse_header(SAT_HEADER)
        for name, key in (("KANSAT_TARGET_MEAN", "target_mean"), ("KANSAT_TARGET_STD", "target_std")):
            if np.float32(sat_parsed[name]).view(np.uint32) != np.float32(reg[key]).view(np.uint32):
                raise SystemExit(f"{name} does not round-trip")
        checks["fp32_round_trip"] = "every array and scalar parses back to the npz FP32 bits"

        # Replica checks over all rows.
        v2, _, _, _, _ = apc.load_v2()
        table = apc.load_physio(ROOT / "outputs/physio-concept-v1")
        x5 = apc.feature_matrix(v2, table, apc.P5)
        valid = table["beat_valid"].to_numpy(bool)
        header_model = apc.models.HeaderKAN(P5_HEADER)
        npz_model = apc.ArrayKAN(p5)
        raw32 = np.where(np.isfinite(x5), x5, as32(parsed["KAN_P5_IMPUTATION_MEAN"])[None, :]).astype(np.float32)
        scaled = header_model.standardize(raw32)
        if not np.all(scaled[~valid] == 0.0):
            raise SystemExit("Imputed rows do not standardize to exactly 0")
        p_header, p_npz = header_model.predict(scaled), npz_model.predict(npz_model.standardize(raw32))
        checks["p5_header_vs_npz_replica_max_abs_p"] = float(np.max(np.abs(p_header - p_npz)))
        sat_model = apc.ArrayKAN({"scaler_mean": reg["scaler_mean"], "scaler_std": reg["scaler_std"],
                                  **header_arrays(SAT_HEADER, "KANSAT")})
        sat_npz = apc.ArrayKAN(reg)

        def s_hat(model):
            out = model._spline(model.output_preactivation(scaled), 2) @ model.p["KAN2_THETA"][0]
            return out * float(np.float32(sat_parsed["KANSAT_TARGET_STD"])) + float(np.float32(sat_parsed["KANSAT_TARGET_MEAN"]))

        s_header, s_npz = s_hat(sat_model), s_hat(sat_npz)
        checks["sat_header_vs_npz_replica_max_abs_s_hat"] = float(np.max(np.abs(s_header - s_npz)))
        torch_resub = pd.read_csv(ROOT / "outputs/physio-device-v1/resubstitution_predictions.csv.gz")
        checks["sat_header_replica_vs_torch_csv_7_significant_digits_max_abs_s_hat"] = float(np.max(np.abs(s_header - torch_resub["s_hat_torch"])))
        checks["p5_npz_replica_vs_torch_max_abs_p_recorded"] = json.loads(
            (ROOT / "outputs/physio-concept-v1/p5_final_model.json").read_text())["replica_vs_torch_max_abs_p"]
        checks["s_hat_range_over_rows"] = [float(s_header.min()), float(s_header.max())]
        checks["s_hat_bounds_analytic"] = list(bounds)
        if checks["p5_header_vs_npz_replica_max_abs_p"] != 0.0 or checks["sat_header_vs_npz_replica_max_abs_s_hat"] != 0.0:
            raise SystemExit(f"Header replica differs from the npz replica: {checks}")

        frame = pd.DataFrame({"row_index": np.arange(len(raw32)), "label": v2["label"].to_numpy(int),
                              "beat_valid": valid.astype(int)})
        for i, name in enumerate(FEATURES):
            frame[name] = [repr(float(v)) for v in raw32[:, i]]
        TABLE_OUT.parent.mkdir(parents=True, exist_ok=True)
        with TABLE_OUT.open("xb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as stream:
            stream.write(frame.to_csv(index=False, lineterminator="\n").encode("utf-8"))
        written.append(TABLE_OUT)
        back = pd.read_csv(TABLE_OUT)
        if not np.array_equal(back[list(FEATURES)].to_numpy(np.float64).astype(np.float32).view(np.uint32), raw32.view(np.uint32)):
            raise SystemExit("Device input table does not round-trip to the FP32 inputs")
        checks["device_input_table_round_trip"] = "FP32 bits equal after pandas read_csv"
        sidecar = {
            "created_utc": datetime.now(timezone.utc).isoformat(), "generator": rel(__file__), "generator_sha256": sha256(__file__),
            "command": " ".join(sys.argv), "numpy": np.__version__, "pandas": pd.__version__, **sources,
            "outputs": {rel(p): sha256(p) for p in (P5_HEADER, SAT_HEADER, TABLE_OUT)},
            "device_input_table": "row_index, label, beat_valid and the five P5 inputs after imputation (beat-invalid rows "
                                  "take the FP32 imputation mean = SCALER_MEAN), as FP32 values: what the device model sees "
                                  "on the offline features",
            "checks": checks,
        }
        with SIDECAR_OUT.open("x", encoding="utf-8") as stream:
            json.dump(sidecar, stream, indent=2)
            stream.write("\n")
        written.append(SIDECAR_OUT)
    except BaseException:
        for path in written:
            path.unlink(missing_ok=True)
        raise
    print(json.dumps({"outputs": sidecar["outputs"], "checks": checks}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
