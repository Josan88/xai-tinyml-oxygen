"""Write a Mean-Perturbation reference header (KAN_XAI_REF_Z) for any TinyKAN weights header.

The device explainer sets one standardized input at a time to a reference value r_i and reports
delta_i = P(x) - P(x with z_i = r_i). Shipped images use r = 0 (the training mean). This script
writes the label-0-median reference: the median standardized input over the table rows whose
label is 0 (for OpenOximetry v2: window-median ScalcO2 >= 90).

Standardization is the firmware formula, z = (x - SCALER_MEAN) / (SCALER_STD + 1e-10), on the
table's values rounded to FP32 and the header's FP32 constants, evaluated in float64 (the
lamaakal_models.HeaderKAN arithmetic, used by the Stage 3 sensitivity check). The float64
median is then rounded to FP32 and written as a literal that round-trips exactly.

Generic: the model header, the table, the feature list (model input order) and the output path
are arguments, so a later model (e.g. P5) reuses this unchanged. Write-once: refuses to overwrite.

v2 (job F1, 30 Oct 2026):
  python scripts/make_xai_reference_header.py \
    --model-header "firmware/Arduino Nano 33/include/kan_model_weights_v2.h" \
    --table outputs/openox-v2/window_features.csv --features v2 \
    --output "firmware/Arduino Nano 33/include/kan_xai_reference_v2.h" \
    --sidecar outputs/xai-reference-headers/kan_xai_reference_v2.json \
    --check-s3 outputs/physio-concept-v1/s3.json --check-s3-model v2
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from train_tinykan_v2 import parse_header  # noqa: E402
from xai_reference import parse_reference_header  # noqa: E402

FEATURE_PRESETS = {
    "v2": ["mean", "std", "minimum", "maximum", "value_range", "rms", "skewness", "kurtosis", "energy",
           "derivative_std", "dominant_frequency_hz", "bandpower_0_5_2_hz", "bandpower_2_5_hz",
           "bandpower_ratio_0_5_2_to_2_5", "ratio_of_ratios", "ir_perfusion_index"],
}
S3_TOLERANCE = 1e-9


def sha256(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def rel(path):
    path = Path(path).resolve()
    return path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else str(path)


def fp32_literal(value):
    """Shortest decimal of the FP32 value; as a C float literal it parses back to the same bits."""
    return repr(float(np.float32(value)))


def label_median(model_header, table, features, label_column, label_value):
    weights = parse_header(model_header)
    mean = np.asarray(weights["SCALER_MEAN"], dtype=np.float32).astype(np.float64)
    std = np.asarray(weights["SCALER_STD"], dtype=np.float32).astype(np.float64)
    if mean.shape != (len(features),):
        raise SystemExit(f"{model_header} has {mean.shape[0]} inputs; --features lists {len(features)}")
    frame = pd.read_csv(table, low_memory=False)
    missing = [name for name in features + [label_column] if name not in frame.columns]
    if missing:
        raise SystemExit(f"{table} lacks columns {missing}")
    raw = frame[features].to_numpy(np.float64).astype(np.float32).astype(np.float64)
    if not np.isfinite(raw).all():
        raise SystemExit("Non-finite feature values in the table; refusing to take a median over them")
    labels = frame[label_column].to_numpy()
    rows = labels == label_value
    if not rows.any():
        raise SystemExit(f"No rows with {label_column} == {label_value}")
    scaled = (raw - mean) / (std + 1e-10)
    return {"mean": mean, "std": std, "rows": int(len(frame)), "reference_rows": int(rows.sum()),
            "z_median": np.median(scaled[rows], axis=0), "raw_median": np.median(raw[rows], axis=0)}


def check_s3(path, model, features, z_median):
    references = json.loads(Path(path).read_text(encoding="utf-8"))["headline"]["references"][model]
    if list(references) != features:
        raise SystemExit(f"{path} references.{model} lists {list(references)}, not --features")
    expected = np.array([references[name]["label0_median_z"] for name in features])
    error = float(np.max(np.abs(z_median - expected)))
    if error > S3_TOLERANCE:
        raise SystemExit(f"Label-0 medians differ from {path} references.{model} by {error:.3e} > {S3_TOLERANCE}; stopping")
    return {"s3": rel(path), "s3_sha256": sha256(path), "model_key": model, "max_abs_diff": error,
            "tolerance": S3_TOLERANCE, "pass": True}


def header_text(args, features, result, literals, sources):
    names = ", ".join(features)
    body = ",\n".join(f"    {literal}f  /* {name} */" for literal, name in zip(literals, features))
    return f"""// Auto-generated by scripts/make_xai_reference_header.py. Do not edit.
// Mean-Perturbation reference for {Path(args.model_header).name}: the {args.tag} reference, the median
// standardized input over the {result['reference_rows']} of {result['rows']} table rows with {args.label_column} == {args.label_value}.
// Not the training mean. Used only by builds with -DOXY_XAI_REF_LABEL0 (kan_inference.h); the
// shipped images do not include this file.
//   model header  {sources['model_header']} sha256 {sources['model_header_sha256']}
//   table         {sources['table']} sha256 {sources['table_sha256']}
// z = (x - SCALER_MEAN) / (SCALER_STD + 1e-10), x and constants FP32, arithmetic float64;
// median in float64, then rounded to FP32. Inputs in model order:
// {names}

#pragma once

#if KAN_INPUT_DIM != {len(features)}
#error "{Path(args.output).name} is the reference for a {len(features)}-input model"
#endif

#define KAN_XAI_REF_TAG "{args.tag}"

const float KAN_XAI_REF_Z[KAN_INPUT_DIM] = {{
{body}
}};
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model-header", type=Path, required=True, help="generated TinyKAN weights header (SCALER_MEAN/STD)")
    parser.add_argument("--table", type=Path, required=True, help="CSV with one column per model input and the label")
    parser.add_argument("--features", required=True,
                        help=f"comma-separated input names in model order, or a preset ({', '.join(FEATURE_PRESETS)})")
    parser.add_argument("--output", type=Path, required=True, help="header to write (fresh)")
    parser.add_argument("--sidecar", type=Path, required=True, help="JSON provenance to write (fresh)")
    parser.add_argument("--label-column", default="label")
    parser.add_argument("--label-value", type=int, default=0)
    parser.add_argument("--tag", default="label0", help="reference tag written as KAN_XAI_REF_TAG")
    parser.add_argument("--check-s3", type=Path, help="s3.json whose headline.references must match to 1e-9")
    parser.add_argument("--check-s3-model", help="key under headline.references, e.g. v2 or P5")
    args = parser.parse_args()
    features = FEATURE_PRESETS.get(args.features) or [f.strip() for f in args.features.split(",") if f.strip()]
    for path in (args.output, args.sidecar):
        if path.exists():
            parser.error(f"{path} exists; refusing to overwrite")
    if bool(args.check_s3) != bool(args.check_s3_model):
        parser.error("--check-s3 and --check-s3-model go together")

    result = label_median(args.model_header, args.table, features, args.label_column, args.label_value)
    z64 = result["z_median"]
    s3 = check_s3(args.check_s3, args.check_s3_model, features, z64) if args.check_s3 else None
    z32 = z64.astype(np.float32)
    literals = [fp32_literal(v) for v in z32]
    parsed = np.array([np.float32(float(text)) for text in literals], dtype=np.float32)
    if not np.array_equal(parsed.view(np.uint32), z32.view(np.uint32)):
        raise SystemExit("FP32 literal does not round-trip")
    sources = {"model_header": rel(args.model_header), "model_header_sha256": sha256(args.model_header),
               "table": rel(args.table), "table_sha256": sha256(args.table)}
    text = header_text(args, features, result, literals, sources)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    tag, reparsed = parse_reference_header(args.output)
    if tag != args.tag or not np.array_equal(reparsed.view(np.uint32), z32.view(np.uint32)):
        args.output.unlink()
        raise SystemExit("Written header does not parse back to the FP32 medians; removed")

    sidecar = {
        "created_utc": datetime.now(timezone.utc).isoformat(), "generator": rel(__file__), "generator_sha256": sha256(__file__),
        "command": " ".join(sys.argv), "python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__,
        "reference": args.tag, "definition": f"median standardized input over rows with {args.label_column} == {args.label_value}",
        "standardization": "z = (x - SCALER_MEAN) / (SCALER_STD + 1e-10); x rounded to FP32; header FP32 constants; float64 arithmetic",
        "rows": result["rows"], "reference_rows": result["reference_rows"], **sources,
        "output": rel(args.output), "output_sha256": sha256(args.output), "s3_check": s3,
        "inputs": {name: {"index": i, "training_mean_raw": float(result["mean"][i]), "training_std_raw": float(result["std"][i]),
                          "label0_median_z_float64": float(z64[i]), "label0_median_z_fp32": float(z32[i]),
                          "fp32_literal": literals[i], "fp32_bits": f"0x{int(z32.view(np.uint32)[i]):08X}",
                          "label0_median_raw": float(result["raw_median"][i]),
                          "label0_median_raw_from_z": float(result["mean"][i] + z64[i] * result["std"][i])}
                   for i, name in enumerate(features)},
        "note": "label0_median_raw is the median of the FP32 raw values; label0_median_raw_from_z maps the z median back "
                "(equal up to rounding, since standardization is increasing). The device holds label0_median_z_fp32.",
    }
    args.sidecar.parent.mkdir(parents=True, exist_ok=True)
    with args.sidecar.open("x", encoding="utf-8") as stream:
        json.dump(sidecar, stream, indent=2)
        stream.write("\n")
    print(json.dumps({"output": sources | {"header": rel(args.output), "header_sha256": sidecar["output_sha256"]},
                      "rows": result["rows"], "reference_rows": result["reference_rows"], "s3_check": s3,
                      "KAN_XAI_REF_Z": dict(zip(features, literals))}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
