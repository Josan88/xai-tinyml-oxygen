"""CPU-only energy-per-decision ESTIMATE from a datasheet current x the measured decision-block time.

NOT A MEASUREMENT. No power instrumentation exists for this project. This multiplies the
nRF52840 Product Specification's typical "CPU running" supply current by the board-measured
(DWT cycle-derived) whole decision-block time and the datasheet's 3 V test supply:

    E = I_CPU x 3 V x t_block

Source of the currents: Nordic Semiconductor, nRF52840 Product Specification v1.1 (4413_417,
2019-02-28), section 5.2.1.3 "CPU running", p. 58; common conditions p. 56 (3 V on VDD, 25 C):
  I_CPU0 = 3.3 mA  CoreMark @ 64 MHz from flash, HFXO, regulator DC/DC
  I_CPU1 = 6.3 mA  CoreMark @ 64 MHz from flash, HFXO, regulator LDO
Which regulator the Arduino mbed core enables on the Nano 33 BLE Sense is not verified here, so
both are reported as a range. CoreMark is an integer workload; this firmware runs FP32 in software
float, so the true current may differ.

Excluded: MAX30102 LED and sensor current, IMU, power LED, board regulator losses, BLE radio,
idle/sleep current between blocks, USB. The block time is DWT cycle-derived on synthetic USB
input and not physically calibrated (D2 GPIO unmeasured).

Reads decision_block_median_ms / _max_ms from outputs/analysis-lamaakal-style-v1/f_deployment.csv.
Writes (write-once) outputs/energy-estimate-v1/{energy_estimate.csv, summary.json, README.md}.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "outputs" / "analysis-lamaakal-style-v1" / "f_deployment.csv"
OUT = ROOT / "outputs" / "energy-estimate-v1"
SUPPLY_V = 3.0
STRIDE_S = 5.0
CURRENTS_MA = {"DC/DC (I_CPU0)": 3.3, "LDO (I_CPU1)": 6.3}
CITATION = ("Nordic Semiconductor, nRF52840 Product Specification v1.1 (4413_417, 2019-02-28), "
            "sec. 5.2.1.3 CPU running, p. 58; common conditions p. 56 (3 V VDD, 25 C)")
LABEL = "estimate, not measured (datasheet CPU current x DWT block time; CPU only)"


def main() -> int:
    if OUT.exists():
        print(f"STOP: {OUT} exists (write-once)")
        return 2
    deployment = pd.read_csv(SOURCE)
    rows = []
    for _, model in deployment[deployment["deployed"] == "yes"].iterrows():
        for regulator, current_ma in CURRENTS_MA.items():
            for statistic in ("median", "max"):
                block_ms = float(model[f"decision_block_{statistic}_ms"])
                energy_mj = current_ma * 1e-3 * SUPPLY_V * block_ms * 1e-3 * 1e3
                rows.append({
                    "model": model["model"], "regulator": regulator, "cpu_current_ma": current_ma,
                    "supply_v": SUPPLY_V, "block_statistic": statistic, "decision_block_ms": round(block_ms, 4),
                    "energy_per_decision_mj": round(energy_mj, 4),
                    "cpu_energy_per_hour_j_at_5s_stride": round(energy_mj * 1e-3 * 3600 / STRIDE_S, 3),
                    "cpu_active_duty_at_5s_stride": round(block_ms / (STRIDE_S * 1e3), 4),
                    "label": LABEL, "current_source": CITATION, "time_source": model["latency_source"],
                })
    table = pd.DataFrame(rows)
    OUT.mkdir(parents=True)
    table.to_csv(OUT / "energy_estimate.csv", index=False, lineterminator="\n")
    summary = {
        "label": LABEL, "formula": "E = I_CPU x 3 V x t_block", "current_source": CITATION,
        "time_source_table": SOURCE.relative_to(ROOT).as_posix(),
        "excluded": ["MAX30102 LEDs and sensor", "IMU", "power LED", "board regulator losses", "BLE radio",
                     "idle/sleep current between blocks", "USB"],
        "caveats": ["regulator mode of the Arduino mbed core not verified: DC/DC and LDO both reported",
                    "CoreMark is integer; firmware is FP32 software float",
                    "block time is DWT cycle-derived on synthetic USB input; D2 GPIO unmeasured"],
        "median_rows": {f"{r.model} | {r.regulator}": r.energy_per_decision_mj
                        for r in table[table.block_statistic == "median"].itertuples()},
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8", newline="\n")
    (OUT / "README.md").write_text(
        "# energy-estimate-v1 (ESTIMATE, NOT MEASURED)\n\n"
        "CPU-only energy per decision = datasheet CPU current x 3 V x board decision-block time. "
        "Generated by `scripts/estimate_energy_datasheet.py`. No power instrumentation was used. "
        "Excludes the sensor LEDs, IMU, power LED, regulator losses, radio and idle current. "
        "Never write it as measured energy.\n", encoding="utf-8", newline="\n")
    print(table[["model", "regulator", "block_statistic", "decision_block_ms", "energy_per_decision_mj",
                 "cpu_energy_per_hour_j_at_5s_stride"]].to_string(index=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
