"""Write the edge-KAN label-0 Mean-Perturbation reference header (EKAN_XAI_REF_Z).

docs/edge-kan-label0-board-preregistration.md. The reference is the in-sample label-0 median the
host analyses use (scripts/edge_kan_additive_deletion.py, `ref0`): inputs standardized by the ekan16
header (edge_kan_paper_analyses.EdgeModel.standardize), median over the label-0 rows of the 48,662-
window table, rounded to FP32. Each value is written as the shortest decimal that parses back to
the same FP32 bits.

Before writing, the script reproduces the registered in-sample candidate values with these 16 floats
(outputs/edge-kan-v1/additive-deletion/aopc_gain_intervals.csv, label0_fp32, mean_perturbation)
and stops unless they match within 1e-9. Write-once: refuses to overwrite either output.

  python scripts/make_edge_kan_xai_reference_header.py
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import edge_kan_paper_analyses as eka  # noqa: E402
import analyze_physio_concept as apc  # noqa: E402
import analyze_panel_addenda_20261110 as addenda  # noqa: E402

HEADER = ROOT / "firmware/Arduino Nano 33/include/edge_kan_xai_reference.h"
SIDECAR = ROOT / "outputs/xai-reference-headers/edge_kan_xai_reference.json"
REGISTERED = ROOT / "outputs/edge-kan-v1/additive-deletion/aopc_gain_intervals.csv"
PREREG = ROOT / "docs/edge-kan-label0-board-preregistration.md"
V2_REFERENCE = ROOT / "firmware/Arduino Nano 33/include/kan_xai_reference_v2.h"
TOL = 1e-9


def sha256(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def rel(path):
    return Path(path).resolve().relative_to(ROOT).as_posix()


def literal(value):
    text = repr(float(np.float32(value)))
    if np.float32(float(text)) != np.float32(value):
        raise SystemExit(f"literal {text} does not round-trip")
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.parse_args()
    for path in (HEADER, SIDECAR):
        if path.exists():
            raise SystemExit(f"{path} exists; refusing to overwrite")

    table = pd.read_csv(eka.P["features"])
    y = table["label"].to_numpy(np.int64)
    raw = table.loc[:, eka.V16].to_numpy(np.float32)
    edge = eka.EdgeModel(eka.P["edge_header"])
    z = edge.standardize(raw)
    ref32 = np.median(z[y == 0], axis=0).astype(np.float32)
    ref = ref32.astype(np.float64)

    # Reproduce the registered host values with exactly these floats.
    p_in, _ = edge.mean_perturbation(z)
    cand = p_in >= eka.THRESHOLD
    _, attr = apc.perturb_against(edge, z, ref)
    fw, rnd = addenda.per_window_aopc(edge, z, attr, ref)
    stored = pd.read_csv(REGISTERED)
    row = stored[(stored.analysis == "in_sample_shipped") & (stored.reference == "label0_fp32")
                 & (stored.subset == "candidate_p_ge_0_50") & (stored.attribution == "mean_perturbation")].iloc[0]
    check = {"candidates": int(cand.sum()), "registered_candidates": int(row.windows),
             "firmware_absolute": float(np.mean(fw[cand])), "registered_firmware_absolute": float(row.firmware_absolute),
             "random_mean": float(np.mean(rnd[cand])), "registered_random_mean": float(row.random_mean)}
    check["pass"] = bool(check["candidates"] == check["registered_candidates"]
                         and abs(check["firmware_absolute"] - check["registered_firmware_absolute"]) <= TOL
                         and abs(check["random_mean"] - check["registered_random_mean"]) <= TOL)
    if not check["pass"]:
        raise SystemExit(f"reference does not reproduce the registered values: {check}")

    lits = [literal(v) for v in ref32]
    v2_text = V2_REFERENCE.read_text(encoding="utf-8")
    same_as_v2 = all(f"{s}f" in v2_text for s in lits)
    p_ref = float(edge.predict(ref[None, :])[0]) if hasattr(edge, "predict") else None

    sources = {"edge_header": rel(eka.P["edge_header"]), "edge_header_sha256": sha256(eka.P["edge_header"]),
               "table": rel(eka.P["features"]), "table_sha256": sha256(eka.P["features"]),
               "preregistration": rel(PREREG), "preregistration_sha256": sha256(PREREG),
               "script_sha256": sha256(Path(__file__))}
    body = "\n".join(f"    {s}f  /* {name} */{',' if i < 15 else ''}" for i, (s, name) in enumerate(zip(lits, eka.V16)))
    text = f"""// Auto-generated by scripts/make_edge_kan_xai_reference_header.py. Do not edit.
// Edge KAN (ekan16) Mean-Perturbation reference: the label-0 median, the median standardized input
// over the {int((y == 0).sum())} of {len(y)} table rows with label == 0. Not the training mean.
// Used only by builds with -DEKAN_XAI_REF_LABEL0 (edge_kan_inference.h); no other image includes it.
// docs/edge-kan-label0-board-preregistration.md.
//   edge header  {sources['edge_header']} sha256 {sources['edge_header_sha256']}
//   table        {sources['table']} sha256 {sources['table_sha256']}
// z = (x - EKAN_SCALER_MEAN) / (EKAN_SCALER_STD + 1e-10), x and constants FP32, arithmetic float64;
// median in float64, then rounded to FP32 (the host's label0_fp32). The 16 values equal
// kan_xai_reference_v2.h: {'yes' if same_as_v2 else 'no'} (the two headers share one scaler).

#pragma once

#if EKAN_INPUT_DIM != 16
#error "edge_kan_xai_reference.h is the reference for the 16-input edge KAN"
#endif

#define EKAN_XAI_REF_TAG "label0"

const float EKAN_XAI_REF_Z[16] = {{
{body}
}};

#define EKAN_XAI_REFERENCE(i) (EKAN_XAI_REF_Z[(i)])
"""
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    SIDECAR.parent.mkdir(parents=True, exist_ok=True)
    sidecar = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
               "python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__,
               "sources": sources, "features": list(eka.V16), "reference_fp32": [float(v) for v in ref32],
               "literals": lits, "p_reference_float64": p_ref, "equals_kan_xai_reference_v2": same_as_v2,
               "registered_reproduction": check, "header": rel(HEADER), "header_sha256": sha256(HEADER)}
    with SIDECAR.open("x", encoding="utf-8") as stream:
        json.dump(sidecar, stream, indent=2)
        stream.write("\n")
    print(json.dumps({"header": rel(HEADER), "header_sha256": sidecar["header_sha256"],
                      "equals_v2": same_as_v2, "p_reference": p_ref, "check": check}, indent=2))


if __name__ == "__main__":
    main()
