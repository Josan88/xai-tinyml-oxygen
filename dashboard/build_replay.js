// Builds replay_windows.js from the 20-row OpenOximetry rubric sample.
// Keeps only what the page shows: window id, firmware probability, top-3 deltas.
// Recording hash, CSV probability, labels, and the CSV explanation are dropped.
//   node dashboard/build_replay.js

const fs = require('fs');
const path = require('path');

const SOURCE = path.join(__dirname, '..', 'outputs', 'openox_tinykan_explanation_rubric_sample.csv');
const TARGET = path.join(__dirname, 'replay_windows.js');

const KEEP = [
  'window_id',
  'firmware_probability',
  'top1_feature', 'top1_delta',
  'top2_feature', 'top2_delta',
  'top3_feature', 'top3_delta',
];

// RFC 4180 subset: quoted fields, doubled quotes, commas inside quotes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows.map((r) => {
    const obj = {};
    header.forEach((h, j) => { obj[h] = r[j]; });
    return obj;
  });
}

function readRows(file = SOURCE) {
  return parseCsv(fs.readFileSync(file, 'utf8'));
}

function slim(row) {
  const out = {};
  KEEP.forEach((k) => {
    out[k] = /_feature$|^window_id$/.test(k) ? row[k] : Number(row[k]);
  });
  return out;
}

if (require.main === module) {
  const rows = readRows().map(slim);
  const body =
    '// Generated by build_replay.js from outputs/openox_tinykan_explanation_rubric_sample.csv.\n' +
    '// 20 real OpenOximetry windows. Do not edit by hand.\n' +
    'const REPLAY_WINDOWS = ' + JSON.stringify(rows, null, 2) + ';\n\n' +
    "if (typeof module !== 'undefined' && module.exports) module.exports = REPLAY_WINDOWS;\n" +
    "if (typeof globalThis !== 'undefined') globalThis.REPLAY_WINDOWS = REPLAY_WINDOWS;\n";
  fs.writeFileSync(TARGET, body);
  console.log('wrote ' + rows.length + ' windows to ' + TARGET);
}

module.exports = { parseCsv, readRows, slim, SOURCE };
